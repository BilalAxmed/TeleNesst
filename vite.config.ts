function teleNestAppBuildPlugin(): Plugin {
  return {
    name: 'telenest-app-build-plugin',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url && req.url.startsWith('/api/offline-package-bundle')) {
          try {
            const distDir = path.resolve(__dirname, 'dist');
            if (!fs.existsSync(distDir) || !fs.existsSync(path.join(distDir, 'index.html'))) {
              res.statusCode = 404;
              res.setHeader('Content-Type', 'application/json');
              res.end(JSON.stringify({ error: 'Production build not found in dist/' }));
              return;
            }
            const html = fs.readFileSync(path.join(distDir, 'index.html'), 'utf-8');
            const assetsDir = path.join(distDir, 'assets');
            const assetFiles = fs.readdirSync(assetsDir).filter(f => !fs.statSync(path.join(assetsDir, f)).isDirectory());
            const assets: Record<string, string> = {};
            for (const file of assetFiles) {
              assets['assets/' + file] = fs.readFileSync(path.join(assetsDir, file), 'utf-8');
            }
            res.setHeader('Content-Type', 'application/json');
            res.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate, proxy-revalidate');
            res.setHeader('Pragma', 'no-cache');
            res.setHeader('Expires', '0');
            res.end(JSON.stringify({ success: true, html, assets, buildTime: new Date().toISOString() }));
            return;
          } catch (err: any) {
            res.statusCode = 500;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ error: err?.message || 'Failed to read dist assets' }));
            return;
          }
        }
        next();
      });
    },
  };
}

