import * as XLSX from 'xlsx';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import QRCode from 'qrcode';
import { CompanyLetterheadConfig, User, SummaryKPI } from '../types';
import { storage } from './storage';

export interface ExportColumn {
  header: string;
  key: string;
  width?: number;
  align?: 'left' | 'center' | 'right';
}

export interface ReportMeta {
  title: string;
  subtitle?: string;
  category?: string;
  dateRange?: string;
  filterSummary?: string;
  currentUser: User;
  companyConfig: CompanyLetterheadConfig;
  summaryCards?: SummaryKPI[];
  moduleName?: string;
}

export class ExportService {
  /**
   * Export tabular data to CSV with UTF-8 BOM
   */
  public static exportToCSV(filename: string, columns: ExportColumn[], data: Record<string, any>[]): void {
    const headers = columns.map((col) => `"${col.header.replace(/"/g, '""')}"`).join(',');
    const rows = data.map((row) =>
      columns
        .map((col) => {
          const val = row[col.key] ?? '';
          const str = String(val).replace(/"/g, '""');
          return `"${str}"`;
        })
        .join(',')
    );

    const csvContent = '\uFEFF' + [headers, ...rows].join('\r\n');
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);
    link.setAttribute('href', url);
    link.setAttribute('download', filename.endsWith('.csv') ? filename : `${filename}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }

  /**
   * Export to native Excel (.xlsx) file with sheet title and meta notes
   */
  public static exportToExcel(
    filename: string,
    sheetName: string,
    columns: ExportColumn[],
    data: Record<string, any>[],
    meta?: ReportMeta
  ): void {
    const wb = XLSX.utils.book_new();

    const formattedData: any[][] = [];

    // Header metadata block
    if (meta) {
      formattedData.push([meta.companyConfig.companyName]);
      formattedData.push([meta.companyConfig.tagline]);
      formattedData.push([`Developed by: ${meta.companyConfig.developedBy}`]);
      formattedData.push([`Official Report: ${meta.title}`]);
      if (meta.dateRange) formattedData.push([`Date Range: ${meta.dateRange}`]);
      if (meta.filterSummary) formattedData.push([`Filters Applied: ${meta.filterSummary}`]);
      formattedData.push([`Generated By: ${meta.currentUser.fullName} (${meta.currentUser.role}) on ${new Date().toLocaleString()}`]);
      formattedData.push([]); // Blank separator
    }

    // Column Headers
    formattedData.push(columns.map((c) => c.header));

    // Data Rows
    data.forEach((row) => {
      formattedData.push(columns.map((c) => row[c.key] ?? ''));
    });

    const ws = XLSX.utils.aoa_to_sheet(formattedData);

    // Set column widths
    ws['!cols'] = columns.map((c) => ({
      wch: Math.max(c.width || 15, c.header.length + 3),
    }));

    XLSX.utils.book_append_sheet(wb, ws, sheetName.substring(0, 31));

    const finalFilename = filename.endsWith('.xlsx') ? filename : `${filename}.xlsx`;
    XLSX.writeFile(wb, finalFilename);
  }

  /**
   * Export to clean, high-precision PDF with executive company letterhead
   */
  public static exportToPDF(
    filename: string,
    columns: ExportColumn[],
    data: Record<string, any>[],
    meta: ReportMeta
  ): void {
    const doc = new jsPDF({
      orientation: columns.length > 6 ? 'landscape' : 'portrait',
      unit: 'mm',
      format: 'a4',
    });

    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();

    // 1. Company Letterhead Header
    doc.setFillColor(15, 23, 42); // Deep executive slate bar
    doc.rect(0, 0, pageWidth, 5, 'F');

    // Accent line (corporate electric blue)
    doc.setFillColor(37, 99, 235);
    doc.rect(0, 5, pageWidth, 1.5, 'F');

    // Branding / Logo Badge
    let textStartX = 14;
    let logoDrawn = false;

    if (meta.companyConfig.logoUrl && meta.companyConfig.logoUrl.startsWith('data:image')) {
      try {
        doc.addImage(meta.companyConfig.logoUrl, 'PNG', 14, 8, 14, 14);
        textStartX = 31;
        logoDrawn = true;
      } catch (err) {
        logoDrawn = false;
      }
    }

    if (!logoDrawn) {
      // Modern corporate emblem
      doc.setFillColor(37, 99, 235);
      doc.roundedRect(14, 8.5, 12, 12, 1.5, 1.5, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8.5);
      doc.setTextColor(255, 255, 255);
      doc.text('TN', 20, 16.5, { align: 'center' });
      textStartX = 29;
    }

    // Company Name
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(15, 23, 42);
    doc.text(meta.companyConfig.companyName.toUpperCase(), textStartX, 14.5);

    // Tagline & System Architecture
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(`${meta.companyConfig.tagline} | Architecture by ${meta.companyConfig.developedBy}`, textStartX, 19);

    // Right-aligned contact & registration block
    doc.setFontSize(7.5);
    doc.setTextColor(71, 85, 105);
    const rightX = pageWidth - 14;
    doc.text(meta.companyConfig.addressLine1, rightX, 11, { align: 'right' });
    doc.text(`${meta.companyConfig.addressLine2} | Tel: ${meta.companyConfig.phone}`, rightX, 15, { align: 'right' });
    doc.text(`TRN: ${meta.companyConfig.taxRegistration} | Reg: ${meta.companyConfig.licenseNumber}`, rightX, 19, { align: 'right' });
    if (meta.companyConfig.email) {
      doc.text(`Email: ${meta.companyConfig.email} | Web: ${meta.companyConfig.website || 'www.telenest.org'}`, rightX, 23, { align: 'right' });
    }

    // Decorative divider
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.4);
    doc.line(14, 25.5, pageWidth - 14, 25.5);

    // 2. Report Information Banner with Official Seal
    const bannerY = 28;
    const bannerH = 17;
    doc.setFillColor(248, 250, 252);
    doc.roundedRect(14, bannerY, pageWidth - 28, bannerH, 1.5, 1.5, 'F');
    doc.setDrawColor(203, 213, 225);
    doc.setLineWidth(0.2);
    doc.roundedRect(14, bannerY, pageWidth - 28, bannerH, 1.5, 1.5, 'S');

    // Official Certified Stamp Badge on right side of banner
    const sealW = 36;
    const sealH = 11;
    const sealX = pageWidth - 14 - sealW - 3;
    const sealY = bannerY + 3;
    doc.setFillColor(15, 23, 42);
    doc.roundedRect(sealX, sealY, sealW, sealH, 1, 1, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(255, 255, 255);
    doc.text('OFFICIAL REPORT', sealX + sealW / 2, sealY + 4.5, { align: 'center' });
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(5.5);
    doc.setTextColor(148, 163, 184);
    doc.text('TELENEST VERIFIED SEAL', sealX + sealW / 2, sealY + 8.5, { align: 'center' });

    // Document Title
    const maxTitleW = sealX - 18 - 4;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text(meta.title, 18, bannerY + 6.5, { maxWidth: maxTitleW });

    // Metadata Subtitle
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    const metaSub = [
      meta.dateRange ? `Period: ${meta.dateRange}` : '',
      meta.filterSummary ? `Scope: ${meta.filterSummary}` : '',
      `Audited by: ${meta.currentUser.fullName} (${meta.currentUser.role})`,
      `Generated: ${new Date().toLocaleString()}`,
    ]
      .filter(Boolean)
      .join('   |   ');
    doc.text(metaSub, 18, bannerY + 12.5, { maxWidth: maxTitleW });

    // 3. Executive Summary KPI Cards (Module Data Summaries)
    let tableStartY = bannerY + bannerH + 4.5;

    if (meta.summaryCards && meta.summaryCards.length > 0) {
      const cards = meta.summaryCards.slice(0, 4);
      const cardsCount = cards.length;
      const gap = 2.5;
      const totalCardsW = pageWidth - 28;
      const cardW = (totalCardsW - (cardsCount - 1) * gap) / cardsCount;
      const cardH = 14;
      const cardsY = bannerY + bannerH + 3.5;

      const accentStripeColors = [
        [37, 99, 235],   // Electric Blue
        [16, 185, 129],  // Emerald Green
        [139, 92, 246],  // Royal Violet
        [245, 158, 11],  // Amber Gold
      ];

      cards.forEach((card, idx) => {
        const cX = 14 + idx * (cardW + gap);
        // Card background
        doc.setFillColor(248, 250, 252);
        doc.roundedRect(cX, cardsY, cardW, cardH, 1, 1, 'F');
        doc.setDrawColor(226, 232, 240);
        doc.setLineWidth(0.2);
        doc.roundedRect(cX, cardsY, cardW, cardH, 1, 1, 'S');

        // Accent indicator stripe on left
        const stripeColor = accentStripeColors[idx % accentStripeColors.length];
        doc.setFillColor(stripeColor[0], stripeColor[1], stripeColor[2]);
        doc.roundedRect(cX, cardsY, 1.4, cardH, 0.4, 0.4, 'F');

        // Card Label
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(6.2);
        doc.setTextColor(100, 116, 139);
        doc.text(card.label.toUpperCase(), cX + 3.2, cardsY + 4, { maxWidth: cardW - 5 });

        // Card Metric Value
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(9.5);
        doc.setTextColor(15, 23, 42);
        doc.text(String(card.value), cX + 3.2, cardsY + 8.5, { maxWidth: cardW - 5 });

        // Card Subtext
        if (card.subtext) {
          doc.setFont('helvetica', 'normal');
          doc.setFontSize(5.5);
          doc.setTextColor(148, 163, 184);
          doc.text(String(card.subtext), cX + 3.2, cardsY + 12, { maxWidth: cardW - 5 });
        }
      });

      tableStartY = cardsY + cardH + 4.5;
    }

    // 4. Render Table
    const tableHeaders = [columns.map((c) => c.header)];
    const tableRows = data.map((row) =>
      columns.map((c) => {
        const val = row[c.key];
        return val !== undefined && val !== null ? String(val) : '-';
      })
    );

    autoTable(doc, {
      head: tableHeaders,
      body: tableRows,
      startY: tableStartY,
      margin: { left: 14, right: 14, bottom: 18 },
      theme: 'grid',
      styles: {
        fontSize: 7.5,
        cellPadding: 2,
        textColor: [30, 41, 59],
        lineColor: [226, 232, 240],
        lineWidth: 0.1,
        overflow: 'linebreak',
      },
      headStyles: {
        fillColor: [15, 23, 42],
        textColor: [255, 255, 255],
        fontStyle: 'bold',
        fontSize: 8,
        halign: 'left',
      },
      alternateRowStyles: {
        fillColor: [248, 250, 252],
      },
      didDrawPage: (hookData) => {
        // Footer with Page numbering and official system seal
        const currentPg = hookData.pageNumber;
        const totalPg = (doc.internal as any).getNumberOfPages();

        doc.setFont('helvetica', 'normal');
        doc.setFontSize(7);
        doc.setTextColor(148, 163, 184);

        // Top line above footer
        doc.setDrawColor(226, 232, 240);
        doc.setLineWidth(0.3);
        doc.line(14, pageHeight - 11, pageWidth - 14, pageHeight - 11);

        // Left footer
        const swName = meta.companyConfig?.softwareName || storage.getSoftwareName();
        doc.text(
          `${swName} Enterprise ICT & Warehouse Operations - Developed by Bilal Ahmed (Official Corporate Record)`,
          14,
          pageHeight - 6.5
        );

        // Right footer
        doc.text(`Page ${currentPg} of ${totalPg}`, pageWidth - 14, pageHeight - 6.5, {
          align: 'right',
        });
      },
    });

    const finalFilename = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
    doc.save(finalFilename);
  }

  /**
   * Opens Print-Friendly View with Company Letterhead
   */
  public static async openPrintLetterhead(
    columns: ExportColumn[],
    data: Record<string, any>[],
    meta: ReportMeta
  ): Promise<{ success: boolean; method: 'popup' | 'iframe' | 'pdf' }> {
    let qrDataUrl = '';
    try {
      qrDataUrl = await QRCode.toDataURL(
        `TELENEST OPERATIONS RECORD\nDoc: ${meta.title}\nRows: ${data.length}\nDate: ${new Date().toISOString()}\nVerified: ${meta.currentUser.fullName} (${meta.currentUser.role})\nDeveloper: ${meta.companyConfig.developedBy}`,
        { width: 180, margin: 1, color: { dark: '#0f172a', light: '#ffffff' } }
      );
    } catch (err) {
      console.warn('QR code generation failed:', err);
    }
    const tableHeadersHtml = columns
      .map(
        (col) =>
          `<th style="padding: 8px 10px; border: 1px solid #cbd5e1; background: #0f172a; color: #fff; text-align: left; font-size: 11px; text-transform: uppercase;">${col.header}</th>`
      )
      .join('');

    const tableRowsHtml = data
      .map(
        (row, idx) =>
          `<tr style="background: ${idx % 2 === 0 ? '#ffffff' : '#f8fafc'};">
            ${columns
              .map(
                (col) =>
                  `<td style="padding: 7px 10px; border: 1px solid #e2e8f0; font-size: 11px; color: #1e293b;">${
                    row[col.key] !== undefined && row[col.key] !== null ? row[col.key] : '-'
                  }</td>`
              )
              .join('')}
          </tr>`
      )
      .join('');

    const html = `
      <!DOCTYPE html>
      <html>
      <head>
        <title>${meta.title} - ${meta.companyConfig?.softwareName || storage.getSoftwareName()} Letterhead</title>
        <style>
          @page { size: auto; margin: 15mm 15mm 15mm 15mm; }
          body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; margin: 0; padding: 20px; color: #0f172a; background: #fff; }
          .header-bar { border-bottom: 2px solid #0f172a; padding-bottom: 12px; margin-bottom: 20px; display: flex; justify-content: space-between; align-items: flex-start; }
          .company-title { font-size: 20px; font-weight: 800; letter-spacing: -0.5px; color: #0f172a; margin: 0; }
          .company-sub { font-size: 11px; color: #64748b; margin-top: 4px; }
          .contact-block { font-size: 10px; color: #475569; text-align: right; line-height: 1.4; }
          .report-banner { background: #f1f5f9; border-left: 4px solid #0f172a; padding: 12px 16px; margin-bottom: 20px; }
          .report-title { font-size: 16px; font-weight: 700; margin: 0 0 6px 0; }
          .report-meta { font-size: 11px; color: #64748b; }
          table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
          .footer-note { border-top: 1px solid #e2e8f0; padding-top: 10px; font-size: 10px; color: #94a3b8; display: flex; justify-content: space-between; }
          @media print {
            .no-print { display: none !important; }
            body { padding: 0; }
          }
        </style>
      </head>
      <body>
        <div class="no-print" style="margin-bottom: 16px; display: flex; gap: 10px; justify-content: flex-end;">
          <button onclick="window.print()" style="padding: 8px 16px; background: #0f172a; color: white; border: none; border-radius: 6px; font-weight: 600; cursor: pointer;">Print / Save as PDF</button>
          <button onclick="window.close()" style="padding: 8px 16px; background: #e2e8f0; color: #334155; border: none; border-radius: 6px; font-weight: 600; cursor: pointer;">Close</button>
        </div>

        <div class="header-bar">
          <div>
            <h1 class="company-title">${meta.companyConfig.companyName}</h1>
            <div class="company-sub">${meta.companyConfig.tagline} | Lead Developer: ${meta.companyConfig.developedBy}</div>
          </div>
          <div class="contact-block">
            <div>${meta.companyConfig.addressLine1}</div>
            <div>${meta.companyConfig.addressLine2}</div>
            <div>Phone: ${meta.companyConfig.phone} | Email: ${meta.companyConfig.email}</div>
            <div>TRN: ${meta.companyConfig.taxRegistration} | Reg: ${meta.companyConfig.licenseNumber}</div>
          </div>
        </div>

        <div class="report-banner" style="display: flex; justify-content: space-between; align-items: center;">
          <div>
            <div class="report-title">${meta.title}</div>
            <div class="report-meta">
              ${meta.dateRange ? `<strong>Date Range:</strong> ${meta.dateRange} &nbsp;|&nbsp; ` : ''}
              ${meta.filterSummary ? `<strong>Filter:</strong> ${meta.filterSummary} &nbsp;|&nbsp; ` : ''}
              <strong>Generated By:</strong> ${meta.currentUser.fullName} (${meta.currentUser.role}) on ${new Date().toLocaleString()}
            </div>
          </div>
          ${
            qrDataUrl
              ? `<div style="text-align: center; margin-left: 16px;">
                  <img src="${qrDataUrl}" style="width: 58px; height: 58px; border: 1px solid #cbd5e1; border-radius: 4px; display: block;" />
                  <div style="font-size: 7.5px; font-weight: 700; color: #475569; margin-top: 2px;">SCAN TO VERIFY</div>
                </div>`
              : ''
          }
        </div>

        <table>
          <thead><tr>${tableHeadersHtml}</tr></thead>
          <tbody>${tableRowsHtml}</tbody>
        </table>

        <div class="footer-note">
          <div>${meta.companyConfig?.softwareName || storage.getSoftwareName()} Telecom Operations Platform - Lead Developer Bilal Ahmed</div>
          <div>Official Operations Record &bull; Confidential</div>
        </div>
      </body>
      </html>
    `;

    // Strategy 1: Hidden iframe printing (compatible with embedded iframe runtime)
    try {
      const iframe = document.createElement('iframe');
      iframe.style.position = 'fixed';
      iframe.style.right = '0';
      iframe.style.bottom = '0';
      iframe.style.width = '0';
      iframe.style.height = '0';
      iframe.style.border = '0';
      document.body.appendChild(iframe);
      const doc = iframe.contentWindow?.document;
      if (doc) {
        doc.open();
        doc.write(html);
        doc.close();
        setTimeout(() => {
          try {
            iframe.contentWindow?.focus();
            iframe.contentWindow?.print();
          } catch (err) {
            console.warn('Iframe print blocked:', err);
          }
          setTimeout(() => {
            if (document.body.contains(iframe)) {
              document.body.removeChild(iframe);
            }
          }, 3000);
        }, 300);
        return { success: true, method: 'iframe' };
      }
    } catch (e) {
      console.warn('Iframe print failed, falling back to direct PDF:', e);
    }

    // Strategy 2: Guaranteed fallback: Direct PDF generation & download
    const cleanFilename = meta.title.replace(/[^a-z0-9]/gi, '_').toLowerCase();
    this.exportToPDF(`${cleanFilename}_letterhead.pdf`, columns, data, meta);
    return { success: true, method: 'pdf' };
  }
}
